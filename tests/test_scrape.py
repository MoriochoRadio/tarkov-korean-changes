class ParseViewNewLayout(unittest.TestCase):
    """개편 후 /view 페이지: data-file-counts JSON + div.diff-content."""

    @classmethod
    def setUpClass(cls):
        cls.raw = s.parse(_read("fixture_view_1239.html"), s.VIEW_URL.format(id=1239))

    def test_meta(self):
        self.assertEqual(self.raw["eft_version"], "1.2.5.0.48146")
        self.assertEqual(self.raw["posted_at"], "Tuesday, 27 October 2026 - 08:43 AM EDT")

    def test_files_changed_from_script_json(self):
        self.assertEqual(self.raw["files_changed"], [
            {"path": "client/items/response.json", "count": 3},
            {"path": "client/locations/response.json", "count": 1},
        ])

    def test_old_style_header_and_body(self):
        lines = self.raw["raw_text"].splitlines()
        self.assertEqual(lines[:6], [
            "Files Changed:",
            "client/items/response.json", "(3 changes)",
            "client/locations/response.json", "(1 change)",
            "Dated: Tuesday, 27 October 2026 - 08:43 AM EDT | Game Version 1.2.5.0.48146",
        ])
        self.assertEqual(lines[6], "client/items/response.json")
        self.assertIn("-            (Old) Superrare", lines)  # 들여쓰기 보존

    def test_no_ui_text_in_body(self):
        rt = self.raw["raw_text"]
        for ui in ("Back to all changes", "CHANGED FILES", "No files match",
                   "Search files", "Expand all", "Latest Changes", "Login with Discord"):
            self.assertNotIn(ui, rt)

    def test_judgements(self):
        rt = self.raw["raw_text"]
        self.assertTrue(s.has_diff(rt))
        self.assertFalse(s.is_locked(rt))
        self.assertFalse(s.is_source_error(rt))
        self.assertEqual(len(st.parse_changes(rt)), 3)


class ParseOtherPages(unittest.TestCase):
    def test_old_layout_still_parses(self):
        raw = s.parse(_read("fixture_latest.html"))
        self.assertEqual(raw["files_changed"], [{"path": "client/globals/response.json", "count": 7}])
        self.assertTrue(raw["raw_text"].startswith("Files Changed"))
        self.assertTrue(s.has_diff(raw["raw_text"]))
        self.assertEqual(raw["eft_version"], "1.0.5.0.45464")

    def test_locked_page(self):
        raw = s.parse(LOCKED_HTML, s.VIEW_URL.format(id=1258))
        self.assertTrue(s.is_locked(raw["raw_text"]))
        self.assertFalse(s.has_diff(raw["raw_text"]))
        self.assertEqual(raw["posted_at"], "Friday, 13 November 2026 - 06:00 AM EST")  # 목록 행에서 보충

    def test_no_diff_page(self):
        raw = s.parse(NO_DIFF_HTML, s.VIEW_URL.format(id=1258))
        self.assertFalse(s.is_locked(raw["raw_text"]))
        self.assertFalse(s.has_diff(raw["raw_text"]))

    def test_list(self):
        rows = s.parse_list(_read("fixture_list.html"))
        self.assertEqual(len(rows), 50)
        by_id = {r["entry_id"]: r for r in rows}
        self.assertEqual(by_id["1239"]["change_count"], 4)
        self.assertEqual(by_id["1243"]["posted_at"], "Friday, 30 October 2026 - 04:58 AM EDT")


class HasDiffAndSourceError(unittest.TestCase):
    def test_has_diff_new_structure_without_header(self):
        body = ("Dated: Friday, 13 November 2026 - 06:00 AM EST | Game Version 1.3.0.1.48558\n"
                "client/survey/response.json\n['data']\n-   (Old) 1\n+   (New) 2")
        self.assertTrue(s.has_diff(body))
        self.assertFalse(s.has_diff("Dated: x | Game Version 1\n설명만 있고 변경 줄 없음"))
        self.assertFalse(s.has_diff(""))
        self.assertFalse(s.has_diff(None))

    def test_source_error(self):
        self.assertTrue(s.is_source_error(CF_ERROR_TEXT))
        self.assertFalse(s.is_source_error("+(New) ['cdn']: cloudflare.example\n+(New) ['x']: 1"))
        self.assertFalse(s.is_source_error(None))


class PipelineHolds(unittest.TestCase):
    """보류 항목 재처리·백필 흐름 — scrape_view/interpret 를 가짜로 바꿔 실행."""

    def setUp(self):
        self._saved = (pipeline.scraper.scrape_view, pipeline.interp.interpret,
                       pipeline.interp.gave_up, pipeline.LLM_GAP_SEC)
        pipeline.ALERTS.clear()
        pipeline.STRUCTURE_SUSPECTS.clear()
        pipeline.LLM_GAP_SEC = 0
        pipeline.interp.gave_up = lambda: None
        self.calls: list[str] = []

        def fake_interpret(raw, notes=None):
            self.calls.append(str(raw["entry_id"]))
            return {**{k: raw.get(k) for k in pipeline.RAW_KEYS},
                    "summary_ko": "가짜 해석", "tags": ["기타"], "changes": [],
                    "is_submarine": True}
        pipeline.interp.interpret = fake_interpret

        good = _read("fixture_view_1239.html")
        pages = {"1240": good, "1241": LOCKED_HTML, "1242": NO_DIFF_HTML, "1243": good}

        def fake_view(eid):
            eid = str(eid)
            raw = s.parse(pages[eid], s.VIEW_URL.format(id=eid))
            raw["entry_id"] = eid
            return raw
        pipeline.scraper.scrape_view = fake_view

    def tearDown(self):
        (pipeline.scraper.scrape_view, pipeline.interp.interpret,
         pipeline.interp.gave_up, pipeline.LLM_GAP_SEC) = self._saved
        pipeline.ALERTS.clear()
        pipeline.STRUCTURE_SUSPECTS.clear()

    @staticmethod
    def _locked(eid):
        return pipeline.make_locked_entry({"entry_id": eid, "scraped_at": "2026-10-29T19:43:54Z",
                                           "raw_text": "⚠️ Access Restricted"})

    def test_reprocess(self):
        entries = [self._locked(x) for x in ("1240", "1241", "1242")]
        cf = {**self._locked("1223"), "tags": [pipeline.HELD_TAG], "raw_text": CF_ERROR_TEXT}
        entries.append(cf)
        self.assertTrue(pipeline.reprocess_locked(entries, []))
        e = {x["entry_id"]: x for x in entries}
        # 1240: 개편 후 페이지 → 잠금 해제로 인정돼 해석, 원래 scraped_at 보존
        self.assertNotIn("locked", e["1240"])
        self.assertEqual(e["1240"]["scraped_at"], "2026-10-29T19:43:54Z")
        self.assertEqual(len(e["1240"]["files_changed"]), 2)
        # 1241: 여전히 잠김 → 유지, 구조 경보 없음
        self.assertTrue(e["1241"]["locked"])
        # 1242: 잠금 안내도 diff 도 없음 → 유지 + 그날 바로 구조 변경 경보
        self.assertTrue(e["1242"]["locked"])
        self.assertEqual(pipeline.STRUCTURE_SUSPECTS, ["1242"])
        # 1223: Cloudflare 오류 본문 → 해석하지 않고 수집오류 보류 + 경보
        self.assertEqual(e["1223"]["tags"], [pipeline.SOURCE_ERROR_TAG])
        self.assertTrue(e["1223"]["locked"])
        self.assertEqual(self.calls, ["1240"])
        self.assertTrue(any("원본 수집 오류" in a for a in pipeline.ALERTS))
        # 수집오류 보류는 다음 실행에서 다시 받지 않는다
        self.calls.clear()
        pipeline.reprocess_locked(entries, [])
        self.assertEqual(self.calls, [])

    def test_backfill_fills_missing_1243(self):
        listing = s.parse_list(_read("fixture_list.html"))
        entries = [{"entry_id": r["entry_id"], "raw_text": ""} for r in listing
                   if r["entry_id"] != "1243"]
        out = pipeline.backfill(entries, listing, lambda: [])
        self.assertEqual(self.calls, ["1243"])
        filled = next(x for x in out if x["entry_id"] == "1243")
        self.assertTrue(filled["backfilled"])
        self.assertFalse(pipeline.STRUCTURE_SUSPECTS)

    def test_store_new_does_not_interpret_unreadable_page(self):
        raw = s.parse(NO_DIFF_HTML, s.VIEW_URL.format(id=1259))
        raw["entry_id"] = "1259"
        out = pipeline.store_new([], raw, lambda: [])
        self.assertEqual(self.calls, [])
        self.assertTrue(out[0]["locked"])
        self.assertEqual(pipeline.STRUCTURE_SUSPECTS, ["1259"])

    def test_alert_message(self):
        pipeline.STRUCTURE_SUSPECTS.append("1242")
        saved_human = list(pipeline.interp.NEEDS_HUMAN)
        try:
            pipeline.report_alerts([])
        finally:
            pipeline.interp.NEEDS_HUMAN[:] = saved_human
        self.assertTrue(any("원본 페이지 구조 변경 의심 — 파서 확인 필요" in a and "1242" in a
                            for a in pipeline.ALERTS))


